'use strict';
// Pre-canned onboarding styles (docs/SPEC.md 1.3 speed rule): styles/index.json lists each style's hero, drone
// and battle plan scripts. buildStyleConfig(player) returns a ready commander-mode arena config (bots.json shape)
// with the player's style plus the 3 unpicked styles as NPC rivals. soft: true marks the 3 NPC seats "soft"
// (config.commander.softHandicap: slower energy refill and battle plan cadence) for the player's first match.
// Each seat also gets the style's default "arsenal" (pre-match drones, SPEC 5.1).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function loadStyles(baseDir = ROOT) {
  const idx = JSON.parse(fs.readFileSync(path.join(baseDir, 'styles', 'index.json'), 'utf8'));
  return { order: idx.order || Object.keys(idx.styles), styles: idx.styles };
}

/** resolve a style key from a key or display name ("Sharpshooter", "sharpshooter", "SHARP" -> no) */
function styleKey(name, styles) {
  const n = String(name || '').trim().toLowerCase();
  for (const [k, s] of Object.entries(styles)) if (k === n || String(s.name).toLowerCase() === n) return k;
  return null;
}

/**
 * @param {string} player style key or name picked by the player
 * @param {{soft?: boolean, softMatches?: number, playerSeat?: string, base?: object, baseDir?: string}} opts
 *   soft: NPC rivals play softer for the first softMatches matches (default 1) after the arena starts; full strength after. playerSeat: seat name for the player (default: the style's name).
 *   base: extra top-level config (tickMs, autoRestart, ...).
 */
function buildStyleConfig(player, opts = {}) {
  const { order, styles } = loadStyles(opts.baseDir);
  const pk = styleKey(player, styles);
  if (!pk) throw new Error(`unknown style "${player}" (choose: ${order.map(k => styles[k].name).join(', ')})`);
  const seat = (k, extra) => {
    const s = styles[k];
    return { hero: s.hero, drones: { ...s.drones }, battlePlan: s.battlePlan, ...(s.arsenal ? { arsenal: { ...s.arsenal } } : {}), color: s.color, style: k, ...extra };
  };
  const seats = {};
  seats[opts.playerSeat || styles[pk].name] = seat(pk, { player: true });
  // soft: NPCs get config.commander.softHandicap, or the player style's own "softRivals" handicap from
  // styles/index.json (tuned per style so every pick wins its first fight about equally often)
  const softness = styles[pk].softRivals ? { handicap: { ...styles[pk].softRivals } } : { soft: true };
  for (const k of order) if (k !== pk) seats[styles[k].name] = seat(k, opts.soft ? softness : {});
  return {
    _comment: `Style match: player = ${styles[pk].name}; NPC rivals = ${order.filter(k => k !== pk).map(k => styles[k].name).join(', ')}${opts.soft ? ' (soft first fight)' : ''}. Generated by src/styles.js.`,
    mode: 'commander', tickMs: 300, autoRestart: true, ...(opts.soft ? { softMatches: opts.softMatches || 1 } : {}), ...(opts.base || {}), seats,
  };
}

/** all 4 styles at full strength (balance testing) */
function allStylesConfig(opts = {}) {
  const { order, styles } = loadStyles(opts.baseDir);
  const seats = {};
  for (const k of order) seats[styles[k].name] = { hero: styles[k].hero, drones: { ...styles[k].drones }, battlePlan: styles[k].battlePlan, ...(styles[k].arsenal && !opts.noArsenal ? { arsenal: { ...styles[k].arsenal } } : {}), color: styles[k].color, style: k };
  return { mode: 'commander', tickMs: 300, autoRestart: true, seats };
}

module.exports = { loadStyles, styleKey, buildStyleConfig, allStylesConfig };
